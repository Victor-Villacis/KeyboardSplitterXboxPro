    // ---- the round-trip guarantee -----------------------------------------

    /// TOML → JSON → TOML, generic over the type, so a NEW config type (or a
    /// new field on an existing one — macros, when they land) is covered by
    /// adding it to the fixture list and nothing else.
    fn round_trip<T>(original: &T)
    where
        T: Serialize + DeserializeOwned + PartialEq + fmt::Debug,
    {
        // The canonical hop, exactly as the store writes it.
        let toml_text = toml::to_string(original).expect("toml render");
        let from_toml: T = toml::from_str(&toml_text).expect("toml parse");
        assert_eq!(&from_toml, original, "TOML did not round-trip\n{toml_text}");

        // ...out to JSON, in both styles...
        for style in [JsonStyle::Pretty, JsonStyle::Compact] {
            let json_text = to_json(&from_toml, style).expect("json render");
            let loaded: Loaded<T> = parse_lenient(&p(), &json_text).expect("json parse");
            assert!(
                loaded.warnings.is_empty(),
                "JSON round-trip warned: {:?}\n{json_text}",
                loaded.warnings
            );
            assert_eq!(
                &loaded.value, original,
                "JSON did not round-trip\n{json_text}"
            );

            // ...and back to canonical TOML, byte-for-byte the same file.
            let back = toml::to_string(&loaded.value).expect("toml re-render");
            assert_eq!(
                back, toml_text,
                "TOML→JSON→TOML changed the file\n{json_text}"
            );
        }
    }


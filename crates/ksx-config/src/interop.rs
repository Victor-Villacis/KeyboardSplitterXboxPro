//! JSON interop — the machine-readable twin of the canonical TOML.
//!
//! # Why TOML is canonical, and JSON is not
//!
//! **Because TOML carries COMMENTS and JSON cannot.** ksx config files are
//! annotated: `mouse_move_deadzone = 5  # 0..12`, the reason a cabinet's
//! `launcher_grace_ms` was raised to 20 s, which panel a `[[device]]` id
//! belongs to. Those notes are the difference between a file a human can
//! maintain a year later and a blob nobody dares touch — and they are the same
//! difference for an AI reading the file, which gets the *intent* alongside the
//! value instead of having to infer it. JSON has no syntax for any of that, so
//! a JSON-canonical ksx would have to throw the annotations away on every
//! write. That decided it; nothing else came close.
//!
//! Two smaller reasons point the same way: TOML is what every existing ksx
//! file, importer, snapshot and doc already is (`docs/research/
//! design-architecture.md` §4.1), and TOML's `[[slot]]`/dotted-key shapes read
//! better by hand than the equivalent nesting.
//!
//! # Why JSON exists anyway
//!
//! For the readers that are not people:
//!
//! - **preset sharing (M7)** — one file, one preset, no ambiguity about
//!   whitespace or comment style, trivially posted through anything;
//! - **AI-generated configs (E5, `docs/ENHANCEMENTS.md`)** — an assistant asked
//!   to wire a cabinet emits JSON reliably; the AI-drivable CLI is the point;
//! - **anything that wants a schema** — a JSON document can be validated,
//!   diffed and generated by tooling that has never heard of TOML.
//!
//! # Why drift is impossible by construction
//!
//! Both formats go through the **same serde types** — [`ConfigFile`],
//! [`GamesFile`], [`PresetFile`]. There is no second schema, no parallel
//! struct, no hand-written JSON writer. A field added to a config type is in
//! both formats the moment it compiles, which is also why the newer shapes
//! (personas, SOCD, chords with `when`/`unless`, multi-key list bindings) need
//! no interop code of their own. That is not a claim, it is a demonstrated
//! one: `[macros.<name>]` landed in [`PresetFile`] while this module was being
//! written and cost the interop layer exactly zero lines — the round-trip
//! tests below picked it up by construction.
//!
//! # Precedence when both exist
//!
//! `config.toml` and `config.json` side by side (or `presets/Foo.toml` and
//! `presets/Foo.json`): **the TOML wins and the JSON is ignored**, with a
//! [`crate::WarningKind::ShadowedByCanonicalToml`] naming the ignored file.
//! They are never merged. A merge would need a rule for every conflicting
//! field, and the first time it guessed wrong it would guess wrong silently —
//! on a file the user believed was authoritative. One winner, said out loud.
//!
//! # The one thing JSON does not get
//!
//! Schema **migration**. [`crate::Store`]'s migration steps operate on a raw
//! `toml::Table`, because the canonical file is the one that has to survive
//! upgrades. A `.json` config whose `schema_version` is not this build's is
//! refused rather than migrated: convert it to TOML, let ksx migrate that, and
//! export JSON again. (Today's registry is empty — v1 is the first schema — so
//! this costs nothing yet; it is written down so it cannot surprise anyone
//! later.)


    #[test]
    fn unknown_keys_warn_instead_of_failing() {
        let json = r#"{"ksx_interop":1,"schema_version":1,"future_part":42,
                       "config":{"schema_version":1,"settings":{"frobnicate":3}}}"#;
        let loaded = parse_document(&p(), json, None).unwrap();
        assert!(loaded.value.config.is_some());
        let paths: Vec<String> = loaded
            .warnings
            .iter()
            .map(|w| match &w.kind {
                WarningKind::UnknownKey { path } => path.clone(),
                other => panic!("unexpected {other:?}"),
            })
            .collect();
        assert!(paths.contains(&"future_part".to_owned()), "{paths:?}");
        // serde_ignored spells the Option hop as `?`; what matters is that the
        // path names the field, deep inside the envelope.
        assert!(
            paths.iter().any(|p| p.ends_with("settings.frobnicate")),
            "{paths:?}"
        );
    }


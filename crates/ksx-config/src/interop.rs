/// Version of the interop ENVELOPE (not of the config schema — that is
/// [`SCHEMA_VERSION`], and it travels in the same document).
///
/// Bumped only when the envelope's own shape changes. A reader refuses a
/// document from the future rather than half-understanding it.
pub const INTEROP_VERSION: u32 = 1;

/// On-disk spelling of a config file.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Format {
    /// Canonical: comments survive, migrations run here.
    Toml,
    /// Interop: machine-generated, machine-read.
    Json,
}

impl Format {
    /// The format a path's extension names, or `None` for anything else.
    pub fn of(path: &Path) -> Option<Self> {
        let ext = path.extension()?.to_str()?;
        if ext.eq_ignore_ascii_case("toml") {
            Some(Self::Toml)
        } else if ext.eq_ignore_ascii_case("json") {
            Some(Self::Json)
        } else {
            None
        }
    }

    /// Extension WITHOUT the dot.
    pub fn extension(self) -> &'static str {
        match self {
            Self::Toml => "toml",
            Self::Json => "json",
        }
    }
}

impl fmt::Display for Format {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.extension())
    }
}

/// Indentation policy for a rendered document.
#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum JsonStyle {
    /// Indented and newline-separated — diffable, reviewable, the default.
    #[default]
    Pretty,
    /// One line, no spare whitespace — for pipes and transports.
    Compact,
}

/// One of the three things a ksx config root holds.
#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]
pub enum Part {
    Config,
    Games,
    Presets,
}

impl Part {
    pub const ALL: [Part; 3] = [Part::Config, Part::Games, Part::Presets];

    pub fn as_str(self) -> &'static str {
        match self {
            Self::Config => "config",
            Self::Games => "games",
            Self::Presets => "presets",
        }
    }

    /// The CLI spelling (`--what config|games|presets`).
    pub fn parse(s: &str) -> Option<Self> {
        match s.trim().to_ascii_lowercase().as_str() {
            "config" => Some(Self::Config),
            "games" => Some(Self::Games),
            "presets" | "preset" => Some(Self::Presets),
            _ => None,
        }
    }
}

impl fmt::Display for Part {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str(self.as_str())
    }
}

/// The interop document: an envelope plus whichever parts it carries.
///
/// Every field is optional, so `--what config` and `--what all` produce the
/// same shape with different fields filled in — one parser on the way back.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct Bundle {
    /// [`INTEROP_VERSION`] — also the marker that makes a document
    /// self-describing (see [`parse_document`]).
    pub ksx_interop: u32,
    /// The config schema these documents belong to ([`SCHEMA_VERSION`]).
    pub schema_version: u32,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub config: Option<ConfigFile>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub games: Option<GamesFile>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub presets: Option<Vec<PresetFile>>,
}

impl Default for Bundle {
    fn default() -> Self {
        Self {
            ksx_interop: INTEROP_VERSION,
            schema_version: SCHEMA_VERSION,
            config: None,
            games: None,
            presets: None,
        }
    }
}

impl Bundle {
    /// Which parts this document actually carries, in a stable order.
    pub fn parts(&self) -> Vec<Part> {
        Part::ALL
            .into_iter()
            .filter(|part| self.has(*part))
            .collect()
    }

    pub fn has(&self, part: Part) -> bool {
        match part {
            Part::Config => self.config.is_some(),
            Part::Games => self.games.is_some(),
            Part::Presets => self.presets.is_some(),
        }
    }

    pub fn is_empty(&self) -> bool {
        self.parts().is_empty()
    }

    /// Drop everything not in `keep`. Used by `--what` on the import side, so
    /// a full backup can be replayed one part at a time.
    pub fn narrow(&mut self, keep: &[Part]) {
        for part in Part::ALL {
            if keep.contains(&part) {
                continue;
            }
            match part {
                Part::Config => self.config = None,
                Part::Games => self.games = None,
                Part::Presets => self.presets = None,
            }
        }
    }

    /// Render. `Pretty` is the default because an exported config is read by
    /// people at least as often as by programs.
    pub fn to_json(&self, style: JsonStyle) -> Result<String, ConfigError> {
        let rendered = match style {
            JsonStyle::Pretty => serde_json::to_string_pretty(self),
            JsonStyle::Compact => serde_json::to_string(self),
        };
        rendered.map_err(|e| ConfigError::JsonRender {
            message: e.to_string(),
        })
    }
}

/// Typed JSON parse that records ignored keys as [`Warning`]s instead of
/// failing — the JSON twin of the store's lenient TOML parse, and lenient for
/// the same reason: a document written by a newer ksx (or by an assistant that
/// guessed one extra field) must degrade to a warning, never to a refusal.
pub fn parse_lenient<T: DeserializeOwned>(
    path: &Path,
    content: &str,
) -> Result<Loaded<T>, ConfigError> {
    let value: serde_json::Value =
        serde_json::from_str(content).map_err(|e| ConfigError::Parse {
            path: path.to_owned(),
            message: e.to_string(),
        })?;
    from_value_lenient(path, value)
}

fn from_value_lenient<T: DeserializeOwned>(
    path: &Path,
    value: serde_json::Value,
) -> Result<Loaded<T>, ConfigError> {
    let mut warnings = Vec::new();
    let parsed = serde_ignored::deserialize(value, |ignored| {
        warnings.push(Warning {
            file: path.to_owned(),
            kind: WarningKind::UnknownKey {
                path: ignored.to_string(),
            },
        });
    })
    .map_err(|e: serde_json::Error| ConfigError::Parse {
        path: path.to_owned(),
        message: e.to_string(),
    })?;
    Ok(Loaded {
        value: parsed,
        warnings,
    })
}

/// Render any config type as JSON. The same value the TOML writer would take,
/// so the two formats cannot disagree about what a type contains.
pub fn to_json<T: Serialize>(value: &T, style: JsonStyle) -> Result<String, ConfigError> {
    let rendered = match style {
        JsonStyle::Pretty => serde_json::to_string_pretty(value),
        JsonStyle::Compact => serde_json::to_string(value),
    };
    rendered.map_err(|e| ConfigError::JsonRender {
        message: e.to_string(),
    })
}

/// Parse an interop document.
///
/// Two shapes are accepted, and which one it is, is DETECTED rather than
/// guessed:
///
/// - **enveloped** — a top-level object carrying `ksx_interop`. It describes
///   itself; `bare` is ignored.
/// - **bare** — a single [`ConfigFile`], [`GamesFile`], [`PresetFile`], or an
///   array of presets. This is what a hand-written or AI-generated file
///   usually looks like, so it is supported — but the type it is cannot be
///   sniffed reliably (a `PresetFile` and a `GamesFile` are both just objects),
///   so `bare` must name it. Without it the document is refused with
///   [`ConfigError::UntaggedJson`] rather than guessed: importing the wrong
///   file over the wrong file is exactly the failure this crate exists to
///   prevent.
pub fn parse_document(
    path: &Path,
    content: &str,
    bare: Option<Part>,
) -> Result<Loaded<Bundle>, ConfigError> {
    let value: serde_json::Value =
        serde_json::from_str(content).map_err(|e| ConfigError::Parse {
            path: path.to_owned(),
            message: e.to_string(),
        })?;

    let enveloped = value
        .as_object()
        .is_some_and(|obj| obj.contains_key("ksx_interop"));
    if enveloped {
        let found = value
            .get("ksx_interop")
            .and_then(serde_json::Value::as_u64)
            .unwrap_or(u64::from(u32::MAX));
        if found > u64::from(INTEROP_VERSION) {
            return Err(ConfigError::UnsupportedInteropVersion {
                path: path.to_owned(),
                found,
                supported: INTEROP_VERSION,
            });
        }
        return from_value_lenient(path, value);
    }

    let Some(part) = bare else {
        return Err(ConfigError::UntaggedJson {
            path: path.to_owned(),
        });
    };
    let mut bundle = Bundle::default();
    let warnings;
    match part {
        Part::Config => {
            let loaded: Loaded<ConfigFile> = from_value_lenient(path, value)?;
            bundle.schema_version = loaded.value.schema_version;
            bundle.config = Some(loaded.value);
            warnings = loaded.warnings;
        }
        Part::Games => {
            let loaded: Loaded<GamesFile> = from_value_lenient(path, value)?;
            bundle.games = Some(loaded.value);
            warnings = loaded.warnings;
        }
        // One preset or a list of them: sharing a single preset is the common
        // case, and a list is what "share my whole panel" wants.
        Part::Presets => {
            if value.is_array() {
                let loaded: Loaded<Vec<PresetFile>> = from_value_lenient(path, value)?;
                bundle.presets = Some(loaded.value);
                warnings = loaded.warnings;
            } else {
                let loaded: Loaded<PresetFile> = from_value_lenient(path, value)?;
                bundle.presets = Some(vec![loaded.value]);
                warnings = loaded.warnings;
            }
        }
    }
    Ok(Loaded {
        value: bundle,
        warnings,
    })
}

/// The schema gate for a `.json` config file.
///
/// The typed parse would fail on a missing `schema_version` anyway; this runs
/// first so the error is the same structured one the TOML path produces, and
/// so an old-schema JSON is refused with the migration advice rather than with
/// a field-by-field type error. See the module docs: JSON is not the migration
/// substrate.
pub fn json_schema_gate(path: &Path, content: &str) -> Result<(), ConfigError> {
    let value: serde_json::Value =
        serde_json::from_str(content).map_err(|e| ConfigError::Parse {
            path: path.to_owned(),
            message: e.to_string(),
        })?;
    let found = match value
        .get("schema_version")
        .and_then(serde_json::Value::as_i64)
    {
        Some(found) => found,
        None => {
            return Err(ConfigError::MissingSchemaVersion {
                path: path.to_owned(),
            })
        }
    };
    if found == i64::from(SCHEMA_VERSION) {
        return Ok(());
    }
    Err(ConfigError::UnsupportedSchemaVersion {
        path: path.to_owned(),
        found,
        supported: SCHEMA_VERSION,
    })
}

